"""Rebuild docs/RESULTS.md from runs/*/ (args.json, log.jsonl, summary.json, noise_eval.json).

usage: python scripts/collect_results.py
"""
import glob
import json
import os
import sys
from datetime import datetime

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

DEFAULTS = {"noise_aware": False, "gate_weight": 0.5, "teacher": [], "causal": False}


def describe(cfg):
    m = cfg["model"]
    parts = [m if not m == "native" else f"native-{cfg['size']}"]
    if m.startswith("bcssm"):
        parts.append("stages=" + ",".join(map(str, cfg.get("ssm_stages", [2, 3]))))
        parts.append(f"N={cfg.get('state', 8)}")
        if cfg.get("noise_aware"):
            parts.append("NASS" + (" (unsupervised gate)" if cfg.get("gate_weight", 0.5) == 0 else f" (λ={cfg.get('gate_weight', 0.5)})"))
    if cfg.get("causal"):
        parts.append("causal")
    if cfg.get("teacher"):
        parts.append("KD←" + "+".join(os.path.basename(t.rstrip("/")) for t in cfg["teacher"]))
    parts.append(f"{cfg['opt']} lr={cfg['lr']} bs={cfg['bs']}")
    return ", ".join(parts)


def main():
    rows = []
    for run in sorted(glob.glob("runs/*/args.json")):
        d = os.path.dirname(run)
        cfg = {**DEFAULTS, **json.load(open(run))}
        recs = [json.loads(l) for l in open(os.path.join(d, "log.jsonl"))] if os.path.exists(os.path.join(d, "log.jsonl")) else []
        evals = [r for r in recs if "test_ema" in r]
        summ = json.load(open(os.path.join(d, "summary.json"))) if os.path.exists(os.path.join(d, "summary.json")) else None
        noise = json.load(open(os.path.join(d, "noise_eval.json"))) if os.path.exists(os.path.join(d, "noise_eval.json")) else None
        params = summ["params"] if summ else None
        if params is None:
            log_path = os.path.join("runs/logs", os.path.basename(d) + ".log")
            if os.path.exists(log_path):
                for line in open(log_path):
                    if " params | " in line:
                        params = int(line.split(": ")[1].split(" params")[0])
        last = evals[-1] if evals else {}
        rows.append({
            "name": os.path.basename(d), "task": cfg["task"], "desc": describe(cfg), "params": params,
            "epochs": f"{len(recs)}/{cfg['epochs']}", "status": "done" if summ else ("stopped" if os.path.exists(os.path.join(d, "STOPPED")) else ("running" if recs else "starting")),
            "best": summ["best_by_valid"]["test"] if summ else None,
            "last_raw": last.get("test_raw"), "last_ema": last.get("test_ema"),
            "gate_acc": recs[-1].get("gate_frame_acc") if recs else None, "noise": noise,
        })

    f = lambda v, p=2: "–" if v is None else (f"{v:.{p}f}" if isinstance(v, float) else str(v))
    out = ["# Results", "", f"_Auto-generated by `scripts/collect_results.py` on {datetime.now():%Y-%m-%d %H:%M}._", "",
           "Test accuracy (%) on the task's test set. **best** = test accuracy of the checkpoint with the best "
           "validation accuracy (the number to report); **last** = final epoch (raw weights / EMA weights). "
           "For running jobs, *last* is the latest evaluation.", ""]
    for task in sorted({r["task"] for r in rows}):
        out += [f"## {task}", "", "| Run | Config | Params | Epochs | Status | Test best | Test last (raw / EMA) | Gate frame acc |",
                "|---|---|---|---|---|---|---|---|"]
        for r in rows:
            if r["task"] == task:
                out.append(f"| `{r['name']}` | {r['desc']} | {f(r['params'])} | {r['epochs']} | {r['status']} | "
                           f"{f(r['best'])} | {f(r['last_raw'])} / {f(r['last_ema'])} | {f(r['gate_acc'], 1)} |")
        noisy = [r for r in rows if r["task"] == task and r["noise"]]
        if noisy:
            keys = list(noisy[0]["noise"].keys())
            out += ["", f"### {task}: noise robustness (test accuracy with GSC background noise mixed at fixed SNR)", "",
                    "| Run | " + " | ".join(keys) + " |", "|---|" + "---|" * len(keys)]
            for r in noisy:
                out.append(f"| `{r['name']}` | " + " | ".join(f(r["noise"][k]) for k in keys) + " |")
        out.append("")
    os.makedirs("docs", exist_ok=True)
    open("docs/RESULTS.md", "w").write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
