"""Export BC-ResNet-8 to ONNX, with int8 calibration data and on-chip test vectors.

Milestone 1 of docs/ONCHIP.md needs three things on the device: the network, a few
real inputs, and the logits the host produced for them. This writes all three into
deploy/onchip/ so the device-side work needs no dataset and no GPU.

usage: python scripts/export_onchip.py
"""
import json, os, numpy as np, torch
from kws.data import LogMel
from kws.train import load_run

OUT = "deploy/onchip"
os.makedirs(OUT, exist_ok=True)
LABELS12 = ["_silence_", "_unknown_", "down", "go", "left", "no", "off", "on", "right", "stop",
            "up", "yes"]
dev = torch.device("cpu")
torch.set_num_threads(4)

model = load_run("runs/v2_12_bcresnet-8", 12, dev, ckpt="best.pt").eval()
fe = LogMel().to(dev)
n_par = sum(p.numel() for p in model.parameters())
print(f"BC-ResNet-8 loaded, {n_par} params")

d = torch.load("cache/gsc_v2_test12.pt")
audio, names = d["audio"], d["class_name"]
with torch.no_grad():
    # --- sanity: accuracy of this exact checkpoint on the full official test set
    y = torch.tensor([LABELS12.index(c) for c in names])
    correct = 0
    feats = []
    for i in range(0, len(audio), 512):
        f = fe(audio[i : i + 512].float() / 32768.0)
        correct += (model(f).argmax(-1) == y[i : i + 512]).sum().item()
        if len(feats) < 1:
            feats.append(f)
    acc = 100 * correct / len(audio)
    print(f"PyTorch float accuracy on the official v2_12 test set: {acc:.2f}%")

    # --- ONNX export, fixed batch 1
    x1 = torch.zeros(1, 1, 40, 101)
    onnx_path = f"{OUT}/bcresnet8.onnx"
    torch.onnx.export(model, (x1,), onnx_path, input_names=["logmel"], output_names=["logits"],
                      opset_version=13, dynamo=False)
    print(f"wrote {onnx_path} ({os.path.getsize(onnx_path)/1024:.0f} KB)")

    # --- calibration set for int8 PTQ: real features, class-balanced
    rng = np.random.default_rng(0)
    pick = rng.permutation(len(audio))[:128]
    calib = fe(audio[pick].float() / 32768.0).numpy().astype(np.float32)
    np.save(f"{OUT}/calib_128.npy", calib)
    print(f"wrote calib_128.npy {calib.shape}")

    # --- test vectors: one clip from each of 4 classes, with PyTorch logits
    want = ["yes", "no", "stop", "_silence_"]
    tv_feat, tv_lab, tv_logits, tv_src = [], [], [], []
    for w in want:
        i = int(next(k for k in pick if names[k] == w)) if any(names[k] == w for k in pick) \
            else int(next(k for k in range(len(names)) if names[k] == w))
        f = fe(audio[i : i + 1].float() / 32768.0)
        lg = model(f)[0]
        tv_feat.append(f[0, 0].numpy()); tv_lab.append(LABELS12.index(w))
        tv_logits.append(lg.numpy()); tv_src.append(d["paths"][i])
        print(f"  {w:10s} -> predicted {LABELS12[int(lg.argmax())]:10s} ({d['paths'][i]})")

np.savez(f"{OUT}/test_vectors.npz", feat=np.stack(tv_feat), label=np.array(tv_lab),
         logits=np.stack(tv_logits), labels=np.array(LABELS12))

# --- C header so the ESP-IDF app needs no file system
with open(f"{OUT}/test_vectors.h", "w") as f:
    f.write("// Generated by scripts/export_onchip.py -- do not edit.\n")
    f.write("// 4 log-mel inputs (40 mel x 101 frames) with the float PyTorch logits they\n")
    f.write("// produced on the host, so an on-chip run can be checked numerically.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write(f"#define TV_COUNT {len(tv_feat)}\n#define TV_MELS 40\n#define TV_FRAMES 101\n")
    f.write(f"#define TV_CLASSES 12\n\n")
    f.write("static const char *const tv_class_names[TV_CLASSES] = {"
            + ", ".join(f'"{l}"' for l in LABELS12) + "};\n\n")
    f.write("static const int tv_expected_label[TV_COUNT] = {"
            + ", ".join(str(l) for l in tv_lab) + "};\n\n")
    f.write("static const float tv_host_logits[TV_COUNT][TV_CLASSES] = {\n")
    for lg in tv_logits:
        f.write("  {" + ", ".join(f"{v:.6f}f" for v in lg) + "},\n")
    f.write("};\n\n")
    f.write("static const float tv_input[TV_COUNT][TV_MELS * TV_FRAMES] = {\n")
    for feat in tv_feat:
        f.write("  {" + ",".join(f"{v:.5f}f" for v in feat.reshape(-1)) + "},\n")
    f.write("};\n")
print(f"wrote test_vectors.h ({os.path.getsize(f'{OUT}/test_vectors.h')/1024:.0f} KB)")

with open(f"{OUT}/export_info.json", "w") as f:
    json.dump({"source_run": "runs/v2_12_bcresnet-8", "ckpt": "best.pt", "params": n_par,
               "float_test_accuracy_v2_12": round(acc, 2), "opset": 13,
               "input": "logmel (1,1,40,101) float32, 40 mel bands, 30 ms window, 10 ms hop",
               "test_vector_sources": tv_src}, f, indent=2)
print("wrote export_info.json")
